import assert from 'node:assert/strict';
import {readFile,lstat} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {indexIdentity} from './index_identity.mjs';
const h=await import('/opt/cirujano/harness.mjs');
const raw=await readFile('/opt/cirujano/image.json','utf8');
const manifest=h.parseStrictJson(raw);
const recipe=h.parseStrictJson(await readFile('/opt/cirujano/recipe.json','utf8'));
const expected={toolSourceSha:'41ddfe532242f87281f9c2ccdd26c7c0f061347a',bundleDigest:'2ada1f090f211f05ac56d69d769e76a3b2dc2e0ebdb75585e81638f88c401dc7',nodeVersion:'22.20.0',pnpmVersion:'10.11.0',harnessHash:'38340b4d15edf20008ca1062e5fbf65522cbd319c9199ab63a10340db1623779',recipeHash:'37a3a20d4ebfb2c7b3cb033e3c5246d1ab46ef0f9b24e93ef0c246079bd072e1',lockfileHash:'eea37020abaf29d8f536bd322c5cd326190e542a3887d18f58c8653d06baa1df'};
for(const [key,value] of Object.entries(expected))assert.equal(manifest[key],value,key);
assert.equal(process.versions.node,expected.nodeVersion);
for(const path of ['/usr/local/bin/pnpm','/home/runner/setup-pnpm/node_modules/.bin/pnpm'])assert.equal(execFileSync(path,['--version'],{encoding:'utf8',timeout:10000}).trim(),expected.pnpmVersion);
assert.equal(h.sha256(await readFile('/opt/cirujano/harness.mjs')),expected.harnessHash);
assert.equal(h.jsonDigest(recipe),expected.recipeHash);
assert.equal(h.sha256(await readFile('/opt/cirujano/dependency-input/pnpm-lock.yaml')),expected.lockfileHash);
const actualStoreHash=await h.dependencyStoreDigest('/opt/cirujano/store');
assert.match(manifest.dependencyStoreHash,/^[a-f0-9]{64}$/);
assert.equal(actualStoreHash,manifest.dependencyStoreHash);
const packagePayloadHash=await h.dependencyStoreDigest('/opt/cirujano/store/v10/files');
assert.equal(packagePayloadHash,'b654033ddabcabb3fe61bd8b647ffe22eef918f6a3ab8103923f8d6bf75d114e');
const normalizedIndexHash=await indexIdentity('/opt/cirujano/store/v10/index',h.jsonDigest);
assert.equal(normalizedIndexHash,'0361b25c392c711092065e289f151248e80c62a48488ab2593db4416066b743a');
for(const path of ['/opt/cirujano/harness.mjs','/opt/cirujano/image.json','/opt/cirujano/store'])assert.equal((await lstat(path)).mode&0o222,0);
console.log(JSON.stringify({schemaVersion:1,kind:'hosted-image-content-readback',manifest,manifestHash:h.jsonDigest(manifest),actualStoreHash,packagePayloadHash,normalizedIndexHash,verified:true}));
